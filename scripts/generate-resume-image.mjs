/* Regenerate the phone view of the resume (public/resume-page-1.webp) from
   public/resume.pdf. Phones cannot show the embedded PDF: iOS Safari draws it at
   full page width, cropped, and Android Chrome draws nothing. Run whenever the
   PDF changes:

     pnpm resume:image

   It also records the PDF's hash in app/resume/preview.ts, and
   app/resume/preview.test.ts fails while the image is older than the PDF.

   Requires poppler and ImageMagick (`brew install poppler imagemagick`). */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PDF = join(ROOT, "public", "resume.pdf");
const OUT = join(ROOT, "public", "resume-page-1.webp");
const MODULE = join(ROOT, "app", "resume", "preview.ts");

const pages = Number(execFileSync("pdfinfo", [PDF], { encoding: "utf8" }).match(/^Pages:\s+(\d+)/m)[1]);
if (pages !== 1) throw new Error(`resume.pdf has ${pages} pages; the phone view shows one`);

const tmp = mkdtempSync(join(tmpdir(), "resume-image-"));
try {
  // 150 dpi puts a letter page at 1275 px wide, enough for a 3x phone screen.
  execFileSync("pdftoppm", ["-r", "150", "-png", "-singlefile", PDF, join(tmp, "page")]);
  execFileSync("magick", [join(tmp, "page.png"), "-quality", "88", OUT]);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const [width, height] = execFileSync("magick", ["identify", "-format", "%w %h", OUT], { encoding: "utf8" })
  .trim()
  .split(" ")
  .map(Number);
const pdfSha256 = createHash("sha256").update(readFileSync(PDF)).digest("hex");

writeFileSync(
  MODULE,
  `/* Generated by scripts/generate-resume-image.mjs from public/resume.pdf. */
export const RESUME_PREVIEW = {
  src: "/resume-page-1.webp",
  width: ${width},
  height: ${height},
  pdfSha256: "${pdfSha256}",
};
`,
);
console.log(`resume-page-1.webp ${width}x${height}, pdf ${pdfSha256.slice(0, 12)}`);
